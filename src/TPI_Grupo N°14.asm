;*******************************************************************************
;Rutina de interrupcion

ISR
		MOVWF   W_TEMP
		SWAPF   STATUS,W
		MOVWF   STATUS_TEMP
		
		;Interrupcion del Teclado
		BANKSEL	INTCON
		BTFSC	INTCON,RBIF
		GOTO	ISR_TECLADO
				
		;Interrupcion del ADC
		BANKSEL	PIR1
		BTFSC	PIR1,ADIF
		GOTO	INTERRUP_ADC
		

ISR_TECLADO
		MOVLW	.1
		MOVWF	CONT
		MOVLW	B'11111101'
		MOVWF	PORTB
LOOP_TECLADO	BTFSS	PORTB,RB4
		GOTO	TEST_RUTINA
		INCF	CONT,F
		BTFSS	PORTB,RB3
		GOTO	TEST_RUTINA
		INCF	CONT,F
		BSF	STATUS,C
		RLF	PORTB,F
		MOVLW	.5
		SUBWF	CONT,W
		BTFSS	STATUS,Z
		GOTO	LOOP_TECLADO
		GOTO	FIN_ISR
		
TEST_RUTINA
		MOVLW	.1
		SUBWF	CONT,F
		BTFSC	STATUS,Z
		GOTO	INTERRUP_RB1
		SUBWF	CONT,F
		BTFSC	STATUS,Z
		GOTO	INTERRUP_RB2
		SUBWF	CONT,F
		BTFSC	STATUS,Z
		GOTO	INTERRUP_RB3
		GOTO	INTERRUP_RB4

		
INTERRUP_RB1	CALL	PRESSED
		MOVLW	B'00000010'
		MOVWF	CONTROL
		
;		BTFSS	PORTB,RB4
;		GOTO	$-1
		GOTO	SALIR_ISR_TECLADO
		
INTERRUP_RB2	CALL	PRESSED
		MOVLW	B'00000100'
		MOVWF	CONTROL
		
;		BTFSS	PORTB,RB3
;		GOTO	$-1
		GOTO	SALIR_ISR_TECLADO	
		
INTERRUP_RB3	CALL	PRESSED
		MOVLW	B'00001000'
		MOVWF	CONTROL
		
;		BTFSS	PORTB,RB4
;		GOTO	$-1
		GOTO	SALIR_ISR_TECLADO

INTERRUP_RB4	CALL	PRESSED
		MOVLW	B'00010000'
		MOVWF	CONTROL
		
;		BTFSS	PORTB,RB3
;		GOTO	$-1
		GOTO	SALIR_ISR_TECLADO
		
PRESSED		BTFSS	PORTB,RB4
		GOTO	PRESSED
		BTFSS	PORTB,RB3
		GOTO	PRESSED
		RETURN

INTERRUP_ADC
		CALL	CONV_BCD
		CALL	NUM_LEDS
		GOTO	SALIR_ISR_ADC
		
SALIR_ISR_TECLADO
		CLRF	PORTB
		BCF	INTCON,RBIF
		GOTO	FIN_ISR
	
SALIR_ISR_ADC
		BANKSEL	PIR1
	    	BCF	PIR1,ADIF
		GOTO	FIN_ISR
FIN_ISR		
		BANKSEL	PORTA
		SWAPF   STATUS_TEMP,W
		MOVWF   STATUS
		SWAPF   W_TEMP,F
		SWAPF   W_TEMP,W
		
		RETFIE
