;*******************************************************************************	
;Subrutinas de Delay
DELAY_1S
	MOVLW	D'255'
	MOVWF	DELAY1	;M
LOOP1	MOVLW	D'241'
	MOVWF	DELAY2	;N
LOOP2	MOVLW	D'1'
	MOVWF	DELAY3	;P
LOOP3	DECFSZ	DELAY3,F
	GOTO	LOOP3
	DECFSZ	DELAY2,F
	GOTO	LOOP2
	DECFSZ	DELAY1,F
	GOTO	LOOP1
	RETURN
	
DELAY_500MS
	MOVLW    D'255'
	MOVWF    DELAY4    ;M
LOOP4   MOVLW    D'241'
	MOVWF    DELAY5    ;N
LOOP5   MOVLW    D'1'
	MOVWF    DELAY6    ;P
LOOP6   DECFSZ    DELAY6,F
	GOTO    LOOP6
	DECFSZ    DELAY5,F
	GOTO    LOOP5
	DECFSZ    DELAY4,F
	GOTO    LOOP4
	RETURN
	
DELAY_5MS	
	MOVLW	D'6'
	MOVWF	DELAY7	;N
LOOP7	MOVLW	D'250'
	MOVWF	DELAY8	;P
LOOP8	DECFSZ	DELAY8,F
	GOTO	LOOP8
	DECFSZ	DELAY7,F
	GOTO	LOOP7
	RETURN	
